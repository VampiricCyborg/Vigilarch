/// §3.3 / §4 — the pack carries exactly the claim's reachable closure: A@0, A@1,
/// and U. Nothing more.
#[test]
fn export_carries_exactly_the_reachable_closure() {
    let h = Honest::build();
    let pack = parse_pack(&pack_scenarios::honest_pack()).unwrap();

    let obs: BTreeSet<Hash> = pack.valid_observations().map(|(id, _, _)| id).collect();
    let att: BTreeSet<Hash> = pack.valid_attestations().map(|(id, _, _)| id).collect();
    assert_eq!(obs, BTreeSet::from([h.a0.id(), h.a1.id()]));
    assert_eq!(att, BTreeSet::from([h.u.id()]));
}

/// §4 — an unrelated observation in the store is not evidence for the claim and
/// MUST NOT appear in the pack.
#[test]
fn export_excludes_records_not_reachable_from_a_claim() {
    let h = Honest::build();
    let mut store = h.store();

    // A stranger writes an entirely unrelated record, and A writes a later entry
    // no attestation in the pack reaches.
    let stranger = SigningKey::from_bytes(&pack_scenarios::seed_stranger());
    let s0 = {
        Observation {
            author: public_key(&stranger),
            site: pack_scenarios::SITE,
            prev: None,
            seq: 0,
            hlc: Hlc::new(1_700_000_000_000, 0),
            body: ObservationBody::Note {
                text: "unrelated: canteen roster for Tuesday".to_owned(),
            },
            geo: None,
            acks: BTreeSet::new(),
        }
    };
    append(&mut store, &s0, &s0.sign(&stranger)).unwrap();
    let a2 = {
        Observation {
            author: public_key(&h.a),
            site: pack_scenarios::SITE,
            prev: Some(h.a1.id()),
            seq: 2,
            hlc: Hlc::new(1_700_000_200_000, 0),
            body: ObservationBody::Note {
                text: "later, unwitnessed entry".to_owned(),
            },
            geo: None,
            acks: BTreeSet::new(),
        }
    };
    append(&mut store, &a2, &a2.sign(&h.a)).unwrap();

    let pack =
        parse_pack(&export_pack(&store, &Quarantine::new(), org_key(), &[h.a0.id()]).unwrap())
            .unwrap();
    let obs: BTreeSet<Hash> = pack.valid_observations().map(|(id, _, _)| id).collect();
    assert!(
        !obs.contains(&s0.id()),
        "the stranger's record is not carried"
    );
    assert!(
        !obs.contains(&a2.id()),
        "A@2 is past the furthest anchored seq (1) and is not carried"
    );
    assert_eq!(obs, BTreeSet::from([h.a0.id(), h.a1.id()]));

    // The pack is byte-identical to the one built without the noise.
    assert_eq!(
        hex::encode(export_pack(&store, &Quarantine::new(), org_key(), &[h.a0.id()]).unwrap()),
        hex::encode(pack_scenarios::honest_pack())
    );
}

/// §2.3 — assembly is deterministic: the same claims over the same held set
/// produce byte-identical output, and adding unreachable noise never changes it.
#[test]
fn export_is_deterministic() {
    let h = Honest::build();
    let a = export_pack(&h.store(), &Quarantine::new(), org_key(), &[h.a0.id()]).unwrap();
    let b = export_pack(&h.store(), &Quarantine::new(), org_key(), &[h.a0.id()]).unwrap();
    assert_eq!(a, b);
}

#[cfg(not(target_family = "wasm"))]
mod property {
    use super::*;
    use proptest::prelude::*;

    proptest! {
        /// Unreachable observations added to the store in any number, with any
        /// bodies, never change the exported pack (§2.3, §4).
        #[test]
        fn noise_never_perturbs_the_pack(texts in proptest::collection::vec("[a-z ]{1,40}", 0..12)) {
            let h = Honest::build();
            let mut store = h.store();
            for (i, text) in texts.iter().enumerate() {
                let sk = SigningKey::from_bytes(&[0x90 ^ (i as u8); 32]);
                let o = Observation {
                    author: public_key(&sk),
                    site: pack_scenarios::SITE,
                    prev: None,
                    seq: 0,
                    hlc: Hlc::new(1_700_000_000_000, 0),
                    body: ObservationBody::Note { text: text.clone() },
                    geo: None,
                    acks: BTreeSet::new(),
                };
                append(&mut store, &o, &o.sign(&sk)).unwrap();
            }
            let pack = export_pack(&store, &Quarantine::new(), org_key(), &[h.a0.id()]).unwrap();
            prop_assert_eq!(hex::encode(pack), hex::encode(pack_scenarios::honest_pack()));
        }
    }
}
