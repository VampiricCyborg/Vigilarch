//! Export-pack assembly, parsing, and the `spec/03-export-pack.md` §6 verdicts.
//!
//! The fixtures under `testdata/packs/` are inputs for `vigil-verify`, which
//! does not exist yet. What these tests assert now is that each fixture *is what
//! the spec says it is*: the honest pack matches the hand-built golden vector
//! byte-for-byte, and each tamper case, run through `vigil-ledger`'s own
//! verification path (`verify_chain`, `Dag::build`, `bracket`), produces the
//! distinct §6.5 verdict it is meant to. Keeping those three verdicts
//! distinguishable is the point of the taxonomy.

#[path = "../testsupport/pack_scenarios.rs"]
mod pack_scenarios;

use std::collections::{BTreeMap, BTreeSet};

use ed25519_dalek::SigningKey;
use vigil_core::{Hash, Hlc, Object, Observation, ObservationBody, SignedObject, public_key};
use vigil_ledger::{
    ChainVerification, ChainViolation, Dag, MemoryStore, Quarantine, Store, WindowEdge, append,
    export_pack, parse_pack, verify_chain,
};

use pack_scenarios::{Honest, org_key};

const GOLDEN: &str = include_str!("../../../testdata/vectors/pack-worked-example.json");
const HONEST: &[u8] = include_bytes!("../../../testdata/packs/honest.vgl");
const T1: &[u8] = include_bytes!("../../../testdata/packs/t1-flipped-byte.vgl");
const T2: &[u8] = include_bytes!("../../../testdata/packs/t2-resigned-genesis.vgl");
const T3: &[u8] = include_bytes!("../../../testdata/packs/t3-dropped-anchor.vgl");
const FORK_WITNESS: &[u8] = include_bytes!("../../../testdata/packs/fork-witness.vgl");
const EARLIEST_HELD: &[u8] = include_bytes!("../../../testdata/packs/earliest-held.vgl");

fn golden_file_hex() -> String {
    let v: serde_json::Value = serde_json::from_str(GOLDEN).expect("golden vector is JSON");
    v["file_hex"].as_str().expect("file_hex").to_owned()
}

/// Rebuild a store from a parsed pack's *surviving* objects — the input to
/// `spec/03` §5 steps 4–6.
fn store_from_pack(pack: &vigil_ledger::PackContents) -> MemoryStore {
    let mut s = MemoryStore::new();
    for (_, obs, sig) in pack.valid_observations() {
        s.put_observation(obs, sig).expect("put");
    }
    for (_, att, sig) in pack.valid_attestations() {
        s.put_attestation(att, sig).expect("put");
    }
    s
}

